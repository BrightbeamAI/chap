/**
 * Generate the owning-profile table each reference dispatches against.
 *
 * SPECIFICATION 15.4 requires a Coordinator to refuse a method whose owning
 * profile the workspace does not advertise. That rule needs one authoritative
 * statement of which profile owns which method, and the catalogue in
 * schemas/profiles/chap-methods.schema.json is it.
 *
 * Two hand-kept copies of that map would drift, exactly as the MCP parameter
 * descriptions did before they were generated, so both references read a
 * generated table and CI fails when a committed copy is stale.
 *
 *   node scripts/sync-method-catalogue.mjs           # write both tables
 *   node scripts/sync-method-catalogue.mjs --check   # fail if either is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CATALOGUE = resolve(root, "schemas/profiles/chap-methods.schema.json");
const TS_OUT = resolve(root, "packages/coordinator/src/catalogue.ts");
const PY_OUT = resolve(root, "packages/coordinator-py/chap_coordinator/catalogue.py");

/**
 * Methods a workspace may call whatever it advertises.
 *
 * Reads, because a workspace must always be able to ask what it is and to
 * check its own chain. audit.verify_chain is attributed to audit-scitt/1.0 but
 * chaining also turns on through an option, so a workspace can be writing a
 * hash-linked chain and be refused permission to verify it. This is a named
 * list rather than the coordinator's read-only set, because that set now holds
 * audit.submit_to_scitt, which reaches a transparency service and is a real
 * audit-scitt/1.0 capability.
 */
const ALWAYS_AVAILABLE = [
  "workspace.describe",
  "audit.read",
  "audit.verify_chain",
  "audit.verify_receipt",
];

const methods = JSON.parse(readFileSync(CATALOGUE, "utf-8")).examples[0].methods;
const owners = Object.entries(methods)
  .filter(([, m]) => m.implementation_status === "implemented")
  .map(([name, m]) => [name, m.since])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

for (const name of ALWAYS_AVAILABLE) {
  if (!owners.some(([m]) => m === name)) {
    console.error(`ALWAYS_AVAILABLE names ${name}, which the catalogue does not implement`);
    process.exit(2);
  }
}

const banner = (comment) => `${comment} Generated by scripts/sync-method-catalogue.mjs. Do not edit.
${comment} Source: schemas/profiles/chap-methods.schema.json`;

const pad = Math.max(...owners.map(([m]) => m.length)) + 3;

// The namespaces whose methods belong to more than one profile, read from the
// catalogue, so the comment below cannot fall out of step with it.
const profilesByNamespace = new Map();
for (const [name, profile] of owners) {
  const ns = name.split(".")[0];
  if (!profilesByNamespace.has(ns)) profilesByNamespace.set(ns, new Set());
  profilesByNamespace.get(ns).add(profile.split("/")[0]);
}
const spans = [...profilesByNamespace]
  .filter(([, profiles]) => profiles.size > 1)
  .map(([ns, profiles]) => {
    const names = [...profiles].sort();
    return `${ns} spans ${names.slice(0, -1).join(", ")} and ${names[names.length - 1]}`;
  });
const spanSentence = `The rule applies to each method, since a namespace can span profiles: ${spans.join("; ")}.`;

/** Wrap a sentence to the given width, each line starting with the prefix. */
function wrap(text, prefix, width = 79) {
  const lines = [];
  let line = prefix;
  for (const word of text.split(" ")) {
    if (line.length + word.length + 1 > width && line.trim() !== prefix.trim()) {
      lines.push(line.trimEnd());
      line = prefix;
    }
    line += (line === prefix ? "" : " ") + word;
  }
  lines.push(line.trimEnd());
  return lines.join("\n");
}

const ts = `${banner("//")}
/**
 * Which profile owns which method, and which methods are never gated.
 *
 * SPECIFICATION 15.4: a Coordinator refuses a method whose owning profile the
 * workspace does not advertise.
${wrap(spanSentence, " * ")}
 */

/** The profile that introduces each method the references implement. */
export const OWNING_PROFILE: Readonly<Record<string, string>> = Object.freeze({
${owners.map(([m, p]) => `  ${`"${m}":`.padEnd(pad)}"${p}",`).join("\n")}
});

/**
 * Callable whatever the workspace advertises.
 *
 * Reads, because a workspace must always be able to ask what it is and to
 * check its own chain. Not the coordinator's read-only set: that holds
 * audit.submit_to_scitt, which reaches a transparency service and is a real
 * audit-scitt/1.0 capability.
 */
export const ALWAYS_AVAILABLE: ReadonlySet<string> = new Set([
${ALWAYS_AVAILABLE.map((m) => `  "${m}",`).join("\n")}
]);
`;

const pyPad = Math.max(...owners.map(([m]) => m.length)) + 3;
const py = `${banner("#")}
"""Which profile owns which method, and which methods are never gated.

SPECIFICATION 15.4: a Coordinator refuses a method whose owning profile the
workspace does not advertise.
${wrap(spanSentence, "")}
"""
from __future__ import annotations

#: The profile that introduces each method the references implement.
OWNING_PROFILE: dict[str, str] = {
${owners.map(([m, p]) => `    ${`"${m}":`.padEnd(pyPad)}"${p}",`).join("\n")}
}

#: Callable whatever the workspace advertises.
#:
#: Reads, because a workspace must always be able to ask what it is and to
#: check its own chain. Not the coordinator's read-only set: that holds
#: audit.submit_to_scitt, which reaches a transparency service and is a real
#: audit-scitt/1.0 capability.
ALWAYS_AVAILABLE: frozenset[str] = frozenset({
${ALWAYS_AVAILABLE.map((m) => `    "${m}",`).join("\n")}
})
`;

const check = process.argv.includes("--check");
let stale = false;
for (const [path, text] of [[TS_OUT, ts], [PY_OUT, py]]) {
  let current = null;
  try { current = readFileSync(path, "utf-8"); } catch { /* not written yet */ }
  if (current === text) continue;
  if (check) { console.error(`Out of date with the catalogue: ${path}`); stale = true; }
  else { writeFileSync(path, text); }
}
if (check && stale) { console.error("Run: node scripts/sync-method-catalogue.mjs"); process.exit(1); }
console.log(check
  ? `Both references agree with the catalogue: ${owners.length} methods, ${ALWAYS_AVAILABLE.length} never gated.`
  : `Wrote the owning-profile table for ${owners.length} methods to both references.`);
