#!/usr/bin/env node
// Build docs/profile-explorer.md from the templates' diff-profiles output.
//
// Each template is generated into a temporary directory and its workload is
// run under every profile set the explorer shows, against Core alone. A
// TypeScript template and a Python template answer the same rows, which is
// checked here, so the page shows one table per profile and names the
// templates it came from.
//
//   node scripts/build-explorer.mjs            write docs/profile-explorer.md
//   node scripts/build-explorer.mjs --check    fail if the file would change
//
// A generated project needs its packages. By default the script links the
// packages in this repository; CHAP_EXPLORER_INSTALL=1 runs npm install and
// pip install against the published packages, which is what CI does.

import { mkdtemp, rm, readFile, writeFile, mkdir, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { generate, listTemplates } from "../index.mjs";

const run = promisify(execFile);
const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..", "..");
const OUT = join(repo, "docs", "profile-explorer.md");

/** The profile sets the explorer shows: each profile added to Core alone. */
export const PROFILES = [
  { id: "review/1.0", title: "review/1.0", what: "a decision on work before it counts as done" },
  { id: "modes/1.0", title: "modes/1.0", what: "shadow, trial and production, and what trial forces" },
  { id: "control/1.0", title: "control/1.0", what: "pause, resume, cancel, snapshot and roll back" },
  { id: "whisper/1.0", title: "whisper/1.0", what: "a quick question with a deadline and a default" },
  { id: "deliberation/1.0", title: "deliberation/1.0", what: "several people deciding under a rule" },
  { id: "handoff/1.0", title: "handoff/1.0", what: "work moving between people" },
  { id: "routing/1.0", title: "routing/1.0", what: "the coordinator choosing an assignee or a review depth" },
  { id: "security-signed/1.0", title: "security-signed/1.0", what: "every call signed by its sender" },
  { id: "audit-scitt/1.0", title: "audit-scitt/1.0", what: "the hash chain, and statements for a transparency service" },
];

const CORE = ["core/1.0"];
/** review/1.0 is in every set except its own row, so the review story runs. */
const withReview = (p) => (p === "review/1.0" ? ["core/1.0", "review/1.0"] : ["core/1.0", "review/1.0", p]);
const baseFor = (p) => (p === "review/1.0" ? CORE : ["core/1.0", "review/1.0"]);

async function prepare(template, dir, install) {
  await rm(dir, { recursive: true, force: true });
  await generate({ name: `explorer-${template.name}`, template: template.name, profiles: template.default_profiles }, { targetDir: dir });
  if (template.language === "typescript") {
    if (install) {
      await run("npm", ["install", "--no-audit", "--no-fund", "--omit=optional"], { cwd: dir });
    } else {
      await mkdir(join(dir, "node_modules", "@brightbeamai"), { recursive: true });
      await mkdir(join(dir, "node_modules", "@modelcontextprotocol"), { recursive: true });
      await symlink(join(repo, "packages", "coordinator"), join(dir, "node_modules", "@brightbeamai", "chap-coordinator"));
      await symlink(join(repo, "packages", "coordinator-mcp"), join(dir, "node_modules", "@brightbeamai", "chap-coordinator-mcp"));
      await symlink(join(repo, "node_modules", "@modelcontextprotocol", "sdk"), join(dir, "node_modules", "@modelcontextprotocol", "sdk"));
    }
  }
}

async function diff(template, dir, profiles, against) {
  const python = process.env.CHAP_PYTHON ?? "python3";
  const args = ["--json", "--profiles", profiles.join(","), "--against", against.join(",")];
  const { stdout } = template.language === "typescript"
    ? await run("node", ["diff-profiles.mjs", ...args], { cwd: dir, maxBuffer: 1 << 24 })
    : await run(python, ["diff-profiles.py", ...args], { cwd: dir, maxBuffer: 1 << 24 });
  return JSON.parse(stdout);
}

export function summary(o) {
  if (o.status !== "ok") return `refused \`${o.code}\``;
  const state = o.result && typeof o.result === "object" ? o.result.state : undefined;
  if (typeof state === "string") return `accepted, \`${state}\``;
  const outcome = o.result && typeof o.result === "object" ? o.result.outcome : undefined;
  return typeof outcome === "string" ? `accepted, outcome \`${outcome}\`` : "accepted";
}

export function render(results) {
  const lines = [];
  lines.push("# What each profile unlocks");
  lines.push("");
  lines.push("Generated by `packages/create-chap-app/scripts/build-explorer.mjs` from the");
  lines.push("templates' `diff-profiles` workload. Each table runs the same calls with");
  lines.push("one profile added to the set and without it, and shows the rows that");
  lines.push("change. The TypeScript and Python templates answer every row the same way,");
  lines.push("which the build checks. The decisions in the workload are scripted; in a");
  lines.push("generated project the decision is made in the desk.");
  lines.push("");
  lines.push("A method a profile owns is refused with `-32601` on a workspace that does");
  lines.push("not advertise the profile. The mode ceiling is enforced on every workspace;");
  lines.push("`modes/1.0` adds the rule that a trial-mode task requires review.");
  lines.push("");
  for (const p of PROFILES) {
    const r = results.find((x) => x.profile === p.id);
    lines.push(`## ${p.title}`);
    lines.push("");
    lines.push(`${p.what[0].toUpperCase() + p.what.slice(1)}. With \`${r.with.join("`, `")}\` against \`${r.without.join("`, `")}\`:`);
    lines.push("");
    lines.push("| Step | Without | With |");
    lines.push("|---|---|---|");
    const changed = r.rows.filter((row) => row.differs);
    for (const row of changed) lines.push(`| ${row.label} | ${summary(row.b)} | ${summary(row.a)} |`);
    if (!changed.length) lines.push("| No row changes in this workload | | |");
    lines.push("");
  }
  lines.push("## Every row");
  lines.push("");
  lines.push("The whole workload under Core alone and under every profile together.");
  lines.push("");
  const all = results.find((x) => x.profile === "all");
  lines.push(`| Step | \`${all.without.join("`, `")}\` | all profiles |`);
  lines.push("|---|---|---|");
  for (const row of all.rows) lines.push(`| ${row.label} | ${summary(row.b)} | ${summary(row.a)} |`);
  lines.push("");
  lines.push(`Templates: ${results[0].templates.join(", ")}.`);
  return lines.join("\n") + "\n";
}

export async function build({ install = !!process.env.CHAP_EXPLORER_INSTALL } = {}) {
  const templates = await listTemplates();
  const ts = templates.find((t) => t.language === "typescript");
  const py = templates.find((t) => t.language === "python");
  const base = await mkdtemp(join(tmpdir(), "chap-explorer-"));
  try {
    const dirs = {};
    for (const t of [ts, py]) { dirs[t.name] = join(base, t.name); await prepare(t, dirs[t.name], install); }
    const sets = [
      ...PROFILES.map((p) => ({ profile: p.id, with: withReview(p.id), without: baseFor(p.id) })),
      { profile: "all", with: ["core/1.0", ...PROFILES.map((p) => p.id)], without: CORE },
    ];
    const results = [];
    for (const s of sets) {
      const a = await diff(ts, dirs[ts.name], s.with, s.without);
      const b = await diff(py, dirs[py.name], s.with, s.without);
      a.rows.forEach((row, i) => {
        const other = b.rows[i];
        if (!other || other.id !== row.id || summary(other.a) !== summary(row.a) || summary(other.b) !== summary(row.b)) {
          throw new Error(`${ts.name} and ${py.name} differ on ${row.id} under ${s.with.join(",")}: ${JSON.stringify(row)} vs ${JSON.stringify(other)}`);
        }
      });
      results.push({ ...s, rows: a.rows, templates: [ts.name, py.name] });
    }
    return render(results);
  } finally {
    await rm(base, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const check = process.argv.includes("--check");
  const text = await build();
  if (check) {
    const current = await readFile(OUT, "utf8").catch(() => "");
    if (current !== text) { console.error(`${OUT} is out of date. Run: node packages/create-chap-app/scripts/build-explorer.mjs`); process.exit(1); }
    console.log(`${OUT} is up to date.`);
  } else {
    await mkdir(dirname(OUT), { recursive: true });
    await writeFile(OUT, text);
    console.log(`Wrote ${OUT}`);
  }
}
